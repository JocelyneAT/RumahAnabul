function setLang(next) {
  lang = next;
  document.documentElement.lang = next;
  try {
    localStorage.setItem("rumahanabul-lang", next);
  } catch {}
}

function escapeHTML(value) {
  return String(value ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
}

// Returns HTML-safe text. Params are escaped; unknown keys (e.g. bad data) are escaped too.
function t(key, params) {
  let text = STRINGS[lang][key] ?? STRINGS.id[key];
  if (text === undefined) return escapeHTML(key);
  if (params) text = text.replace(/\{(\w+)\}/g, (_, name) => escapeHTML(params[name]));
  return text;
}
